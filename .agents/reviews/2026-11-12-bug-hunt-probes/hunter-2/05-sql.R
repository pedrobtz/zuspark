run <- function(title, streams, unary = list(), f) {
  cat("##", title, "\n")
  srv <- new_server(streams, unary); con <- srv$connect()
  r <- try_show(f(con)); if (!inherits(r, "condition")) { if (is.data.frame(r)) { cat("   df", nrow(r), "x", ncol(r), "\n"); print(head(r, 3)) } else print(r) }
  srv$show()
  invisible(list(srv = srv, r = r, con = con))
}
