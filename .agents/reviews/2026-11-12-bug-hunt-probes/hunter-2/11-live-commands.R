go <- function(s, show = TRUE) {
  cat("##", substr(gsub("\\s+", " ", s), 1, 110), "\n"); px$log <- list()
  x <- try_show(spark_sql(con, s))
  if (is.data.frame(x)) { cat("   data.frame", nrow(x), "x", ncol(x), "\n"); if (show && nrow(x)) print(head(x, 3)) }
  else if (inherits(x, "zuspark_query")) { cat("   query; relation kind:", names(x$relation), "\n"); d <- try_show(spark_collect(x)); if (is.data.frame(d)) { cat("   collected", nrow(d), "x", ncol(d), " q$rows", x$rows, "\n"); if (show) print(head(d, 3)) } }
  px$show(TRUE); invisible(x)
}
