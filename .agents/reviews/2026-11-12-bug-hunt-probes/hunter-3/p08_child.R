source("pre.R")
con <- spark_connect(URL)
cat("SID", con$session_id, "\n")
q <- spark_sql(con, "SELECT sum(id % 7) AS s FROM range(30000000000000)")
t0 <- Sys.time()
# trace reattaches
trace(zuspark:::reattach_execute, tracer = quote(cat("REATTACH at", round(as.numeric(Sys.time() - t0, units = "secs")), "s; responses so far:", run$responses, "\n")), print = FALSE, where = asNamespace("zuspark"))
e <- tryCatch(spark_collect(q), condition = function(e) e)
cat("after", round(as.numeric(Sys.time() - t0, units = "secs"), 1), "s; class:", paste(class(e), collapse = "/"), "\n")
cat("msg:", conditionMessage(e), "\n")
cat("op:", q$operation_id, " ids:", e$interrupted_ids, "\n")
r <- tryCatch(spark_collect(spark_sql(con, "SELECT 5 AS x"))$x, condition = function(e) conditionMessage(e))
cat("usable after:", r, "\n")
cat("disc:", tryCatch(spark_disconnect(con), condition = function(e) conditionMessage(e)), "\n")
