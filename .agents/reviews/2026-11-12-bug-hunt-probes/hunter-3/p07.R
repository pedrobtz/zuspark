source("pre.R")
# server restart noticed by each verb
con <- spark_connect(URL); con3 <- spark_connect(URL); con4 <- spark_connect(URL)
q <- spark_sql(con, "SELECT id FROM range(3)"); spark_collect(q)
err <- tryCatch(spark_sql(con, "SELECT * FROM nope"), error = function(e) e)
d <- DBI::dbConnect(spark_driver(), con = con3)
res <- DBI::dbSendQuery(d, "SELECT 1 AS x")
print(spark_session_id(con))
system("podman restart hunt3-spark >/dev/null 2>&1")
repeat { Sys.sleep(2); if (any(grepl("Spark Connect server started", system("podman logs --since 20s hunt3-spark 2>&1", intern = TRUE)))) break }
Sys.sleep(1)
say("--- collect"); tc(spark_collect(q)); say("q rows after failed run: %s; op %s", format(q$rows), q$operation_id)
say("--- collect again"); tc(spark_collect(q))
say("--- sql"); tc(spark_sql(con, "SELECT 1"))
say("--- schema"); tc(spark_schema(q))
say("--- config"); tc(spark_config(con))
say("--- interrupt"); tc(spark_interrupt(con))
say("--- details"); tc(spark_error_details(err))
say("--- execute"); tc(spark_execute(con, "SELECT 1"))
print(con); print(spark_session_id(con))
say("--- dbFetch"); tc(DBI::dbFetch(res)); say("valid con %s res %s", DBI::dbIsValid(d), DBI::dbIsValid(res))
say("--- dbGetQuery"); tc(DBI::dbGetQuery(d, "SELECT 1"))
say("--- dbDisconnect"); print(tc(DBI::dbDisconnect(d))); say("valid con %s", DBI::dbIsValid(d))
say("--- disconnect"); print(tc(spark_disconnect(con))); print(con); say("chan=%d", nchan())
say("--- con4: disconnect as first call after restart"); print(tc(spark_disconnect(con4))); say("chan=%d", nchan())
