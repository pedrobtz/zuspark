rt <- function(x, type = NULL) {  # roundtrip through dbQuoteLiteral
  lit <- as.character(dbQuoteLiteral(con, x))
  sql <- paste0("SELECT * FROM VALUES ", paste0("(", lit, ")", collapse = ", "), " AS t(v)")
  dbGetQuery(con, sql)$v
}
cmp <- function(label, x, eq = function(a, b) identical(a, b)) {
  r <- t(rt(x), FALSE)
  if (inherits(r, "err")) return(invisible())
  ok <- isTRUE(eq(x, r))
  cat(sprintf("%-5s %s\n", if (ok) "ok" else "DIFF", label))
  if (!ok) { cat("   in : "); cat(deparse(x, control = "digits17"), "\n"); cat("   out: "); cat(deparse(r, control = "digits17"), "\n"); cat("   sql: ", head(as.character(dbQuoteLiteral(con, x)), 4), "\n") }
}
